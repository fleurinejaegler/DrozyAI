# CLI demo
# ----------------------------------------------------------------------
if __name__ == "__main__":
    samples = [
        {"risk_score": 0.85, "trend": 0.10, "top_signals": ["perclos", "blink_rate"]},
        {"risk_score": 0.60, "trend": 0.15, "top_signals": ["rmssd", "ear_mean"]},
        {"risk_score": 0.55, "trend": -0.05, "top_signals": ["ear_mean"]},
        {"risk_score": 0.20, "trend": 0.00, "top_signals": []},
    ]
    for s in samples:
        result = advisor(**s)
        print(f"risk={s['risk_score']:.2f} trend={s['trend']:+.2f}")
        print(f"  action: {result['action']}")
        print(f"  reason: {result['reason']}")
        print(f"  source: {result.get('source', 'unknown')}")
        print()