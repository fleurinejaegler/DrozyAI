"""Local LLM advisor for the DrozyAI system.

Architecture:
    1. The rule-based advisor decides the ACTION (deterministic, safe).
    2. The local LLM generates the REASON (natural language, human-friendly).
    3. If the LLM is unavailable, the rule-based reason is used.

This guarantees the action is always correct, while still showing the
on-device LLM for natural-language advice.

Environment variables:
    LLM_BASE_URL  (default: http://localhost:11434/v1)
    LLM_MODEL     (default: llama3.2:3b)
    LLM_TIMEOUT   (default: 10 seconds)

Usage:
    python -m src.advisor.nemotron_client
"""

from __future__ import annotations

import json
import os
from typing import Any

import requests

from src.advisor.fallback import rule_based_advisor


# ----------------------------------------------------------------------
# Configuration
# ----------------------------------------------------------------------
BASE_URL = os.environ.get("LLM_BASE_URL", "http://localhost:11434/v1")
MODEL = os.environ.get("LLM_MODEL", "llama3.2:3b")
TIMEOUT = float(os.environ.get("LLM_TIMEOUT", "10"))


SYSTEM_PROMPT = """You are a drowsy-driving safety advisor.

You will receive a JSON object with:
- current_risk: float in [0, 1]
- trend: signed change in risk over the last 10 minutes
- top_signals: list of strings naming the strongest contributing signals
- action: the action that has ALREADY been decided for you

Your job is ONLY to write a short, clear, one-sentence reason for the given action.
Do not change the action.

Respond with JSON only, exactly in this form:
{"reason": "<one short sentence>"}
"""


# ----------------------------------------------------------------------
# LLM call
# ----------------------------------------------------------------------
def _call_llm(payload: dict[str, Any]) -> dict[str, str]:
    """Call the LLM and return the parsed JSON response."""
    user_prompt = json.dumps(
        {
            "current_risk": round(float(payload["current_risk"]), 3),
            "trend": round(float(payload["trend"]), 3),
            "top_signals": list(payload.get("top_signals", [])),
            "action": payload["action"],
        }
    )

    response = requests.post(
        f"{BASE_URL}/chat/completions",
        json={
            "model": MODEL,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
            "temperature": 0.3,
            "max_tokens": 80,
        },
        timeout=TIMEOUT,
    )
    response.raise_for_status()

    data = response.json()
    content = data["choices"][0]["message"]["content"].strip()

    # Strip markdown fences if the model added them
    if content.startswith("```"):
        content = content.strip("`")
        if content.startswith("json"):
            content = content[4:].strip()

    return json.loads(content)


# ----------------------------------------------------------------------
# Public API
# ----------------------------------------------------------------------
def llm_advisor(
    risk_score: float,
    trend: float = 0.0,
    top_signals: list[str] | None = None,
) -> dict[str, str]:
    """Return the final recommendation.

    The action is decided by the rule-based advisor.
    The reason is generated by the LLM when available.
    """
    top_signals = top_signals or []

    # 1. Rule decides the action
    rule_result = rule_based_advisor(risk_score, trend, top_signals)
    action = rule_result["action"]

    # 2. LLM generates the reason
    try:
        result = _call_llm(
            {
                "current_risk": risk_score,
                "trend": trend,
                "top_signals": top_signals,
                "action": action,
            }
        )
        reason = result.get("reason", rule_result["reason"])
        if not isinstance(reason, str) or not reason.strip():
            reason = rule_result["reason"]
        return {"action": action, "reason": reason, "source": "llm_reason"}
    except Exception as exc:  # noqa: BLE001
        return {
            "action": action,
            "reason": rule_result["reason"],
            "source": f"fallback_error: {type(exc).__name__}",
        }


def advisor(
    risk_score: float,
    trend: float = 0.0,
    top_signals: list[str] | None = None,
) -> dict[str, str]:
    """Public entry point. Alias for llm_advisor()."""
    return llm_advisor(risk_score, trend, top_signals)


